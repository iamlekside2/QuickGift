// A few icons read better filled (ratings etc.).
const FILLED = new Set(['star', 'star-half', 'heart']);

/**
 * Drop-in replacement for @expo/vector-icons Ionicons -- same props
 * (name, size, color, style) but renders lucide-react-native icons.
 */
export function Ionicons({ name, size = 22, color = '#000', style }) {
  const Cmp = MAP[name] || Circle;
  const filled = FILLED.has(name);
  return (
    <Cmp
      size={size}
      color={color}
      fill={filled ? color : 'none'}
      strokeWidth={2}
      style={style}
    />
  );
}

export default Ionicons;
